export function loadPrompts(): ScriptAnalysisPrompts {
  try {
    const stored = localStorage.getItem(STORAGE_KEY)
    if (stored) {
      const parsed = JSON.parse(stored)
      if (!parsed._version || parsed._version < PROMPT_VERSION) {
        console.log(`[PromptStorage] 提示词版本过旧 (${parsed._version || 0} < ${PROMPT_VERSION})，使用新默认值`)
        const defaults = getDefaultPrompts()
        localStorage.setItem(STORAGE_KEY, JSON.stringify(defaults))
        return defaults
      }
      return {
        ...getDefaultPrompts(),
        ...parsed,
      }
    }
  } catch (err) {
    console.error('[PromptStorage] 加载提示词失败:', err)
  }
  return getDefaultPrompts()
}

export function savePrompts(prompts: ScriptAnalysisPrompts): void {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify({ ...prompts, _version: PROMPT_VERSION }))
    console.log('[PromptStorage] 提示词已保存')
  } catch (err) {
    console.error('[PromptStorage] 保存提示词失败:', err)
  }
}

export function resetPrompts(): ScriptAnalysisPrompts {
  const defaults = getDefaultPrompts()
  savePrompts(defaults)
  return defaults
}
