/**
 * 根据风格名获取风格描述
 * 如果风格有自定义预设，返回详细描述；否则返回简单的风格名
 */
export function getStyleInfo(style: string): string {
  const preset = STYLE_PRESETS[style]
  if (preset) {
    return preset
  }
  return `\n\n风格：${style}`
}
